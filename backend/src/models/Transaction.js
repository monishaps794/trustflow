const mongoose = require('mongoose');

const transactionSchema = new mongoose.Schema({
  sender: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  senderAccountNumber: { type: String, required: true },
  recipientName: { type: String, required: true },
  recipientBankName: { type: String, default: 'Not provided', trim: true },
  recipientAccount: { type: String, required: true },
  amount: { type: Number, required: true },
  purpose: { type: String, required: true },
  transactionType: { type: String, default: 'TRANSFER' },
  status: { type: String, enum: ['PENDING', 'AWAITING_EMAIL_VERIFICATION', 'AWAITING_ADMIN_APPROVAL', 'AWAITING_PAYMENT', 'PENDING_PAYMENT', 'PENDING_ADMIN_APPROVAL', 'APPROVED_PAYMENT_AVAILABLE', 'COMPLETED', 'FAILED', 'REJECTED', 'BLOCKED'], default: 'PENDING' },
  paymentStatus: { type: String, enum: ['PENDING', 'PAID', 'FAILED', 'REJECTED'], default: 'PENDING' },
  paymentOrderId: { type: String, default: '' },
  paymentId: { type: String, default: '' },
  paymentReference: { type: String, default: '' },
  currency: { type: String, default: 'INR' },
  paymentMethod: { type: String, default: '' },
  paymentFailureReason: { type: String, default: '' },
  paymentFailureCode: { type: String, default: '' },
  approvalStatus: { type: String, enum: ['NOT_REQUIRED', 'PENDING', 'APPROVED', 'REJECTED'], default: 'NOT_REQUIRED' },
  adminApprovalStatus: { type: String, enum: ['NOT_REQUIRED', 'PENDING', 'APPROVED', 'REJECTED'], default: 'NOT_REQUIRED' },
  adminApprovedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'Admin', default: null },
  adminApprovedAt: { type: Date, default: null },
  adminRejectedAt: { type: Date, default: null },
  riskScore: { type: Number, default: 0 },
  riskLevel: { type: String, default: 'LOW' },
  riskReasons: [{ type: String }],
  emailVerified: { type: Boolean, default: false },
  emailVerificationStatus: { type: String, enum: ['PENDING', 'APPROVED', 'REJECTED', 'NOT_REQUIRED'], default: 'NOT_REQUIRED' },
  emailVerificationTokenHash: { type: String, default: null },
  emailVerificationExpiresAt: { type: Date, default: null },
  emailVerificationUsedAt: { type: Date, default: null },
  userVerificationAt: { type: Date, default: null },
  isBlocked: { type: Boolean, default: false },
  createdAt: { type: Date, default: Date.now },
  approvedAt: { type: Date, default: null },
  rejectedAt: { type: Date, default: null },
  relatedAlert: { type: mongoose.Schema.Types.ObjectId, ref: 'Alert', default: null },
}, { timestamps: true });

module.exports = mongoose.model('Transaction', transactionSchema);
